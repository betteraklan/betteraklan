// Lists the places categoryOf() could not class (Other), for a person to review.
// Run: npx tsx scripts/data-prep/list-other-categories.ts
// Writes docs/tourism-category-review.md. Reads the data; never writes it.
import { writeFileSync } from 'node:fs';

import boundaries from '../../src/data/geo/municipalities-boundaries.json';
import centroids from '../../src/data/geo/municipality-centroids.json';
import accommodations from '../../src/data/tourism/accommodations.json';
import municipalities from '../../src/data/tourism/municipalities.json';
import resorts from '../../src/data/tourism/resorts.json';
import {
  categoryOf,
  CATEGORIES,
  leadSentence,
} from '../../src/lib/tourism/category';
import { buildRecords } from '../../src/lib/tourism/explore';

const records = buildRecords({
  municipalities,
  resorts,
  accommodations,
  centroids,
  boundaries: (boundaries as { features: never[] }).features,
} as never).filter(
  r => r.layer === 'place' && r.town && r.id.split('-')[0] === 'place'
);

const counts = Object.fromEntries(CATEGORIES.map(c => [c, 0])) as Record<
  string,
  number
>;
const other = records.filter(r => {
  const c = categoryOf(r);
  counts[c] += 1;
  return c === 'Other';
});

const first = (s: string) => leadSentence(s).replace(/\|/g, '\\|');

const lines = [
  '# Places the category rules could not class',
  '',
  'These are the places `categoryOf()` (src/lib/tourism/category.ts) put in **Other** because their name and first sentence do not name a beach, falls, cave, culture or nature feature. Each needs a person to decide whether a rule should cover it or it really is Other. Generated by `npx tsx scripts/data-prep/list-other-categories.ts`; the data files are not changed.',
  '',
  `Places by category: ${CATEGORIES.map(c => `${c} ${counts[c]}`).join(', ')} (${records.length} places).`,
  '',
  `## Other (${other.length})`,
  '',
  '| Record | Town | Name | First sentence of the description |',
  '| --- | --- | --- | --- |',
  ...other.map(
    r =>
      `| ${r.recordId ?? r.id} | ${r.townName} | ${r.name.replace(/\|/g, '\\|')} | ${first(r.description)} |`
  ),
  '',
];
writeFileSync('docs/tourism-category-review.md', lines.join('\n'));
console.log(
  `Wrote docs/tourism-category-review.md: ${other.length} Other of ${records.length} places`
);
